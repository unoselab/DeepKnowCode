LOG_DIR="$ROOT/logs/g-03/gpt-oss-120b"
LOG_PREFIX="g-03d-v1"
LOG_TIMESTAMP_FORMAT='+%Y-%m%d-%H%M%S'
RESULTS_DIR="$ROOT/results/g-03/gpt-oss-120b"
